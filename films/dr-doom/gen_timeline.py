"""timeline.js + cues.json (narration subtitles, not burned in) from voice durations."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
dur = json.load(open(f'{HERE}/voice/dur.json'))
lines = {l['id']: l for l in json.load(open(f'{HERE}/lines.json'))}
VO = {'v1': 0.9, 'v2': 6.6, 'v3': 14.6, 'v4': 23.9, 'v5': 34.6, 'v6': 43.4, 'v7': 51.8}
for k, t in VO.items(): print(k, t, round(t + dur[k], 2))
ev = [{'t': t, 'type': 'voice', 'id': k} for k, t in VO.items()]
def E(t, k, **kw): ev.append({'t': t, 'type': k, **kw})
# 01
E(.3, 'tick'); E(.6, 'sub', v=1)
for i in range(6): E(1.0 + i * .2, 'type', v=1)
E(2.45, 'lock'); E(1.8, 'hum', d=4.2); E(3.6, 'type', v=.6); E(4.3, 'shatter', v=.7)
# 02
E(6.0, 'boom', v=.8)
for i in range(8): E(7.25 + i * .1, 'clack', v=.6)
E(9.0, 'type', v=1); E(9.35, 'ink'); E(10.2, 'type', v=1); E(10.3, 'shimmer', d=1.4); E(11.4, 'type', v=1); E(11.55, 'tear'); E(12.4, 'tick')
# 03
E(14.0, 'slam', v=.8); E(15.0, 'burst'); E(15.0, 'pulse', d=8.0)
for i in range(7): E(17.5 + i * .09 + .16, 'clack', v=.7)
E(19.2, 'whoosh'); E(19.55, 'slam', v=.7); E(20.5, 'boom', v=.7); E(21.72, 'stamp')
# 04
E(23.0, 'clack', v=.6); E(23.6, 'tick'); E(23.2, 'machine', d=6.8)
E(28.0, 'warble', d=2.0); E(29.55, 'tink'); E(30.45, 'collapse'); E(30.86, 'slam', v=1.0); E(31.6, 'shatter', v=1)
# 05
E(33.0, 'drone', d=9.0, kind='sub'); E(33.8, 'thud', v=.7); E(34.5, 'swell', d=2.2); E(36.5, 'crush'); E(37.3, 'tick'); E(37.8, 'crackle', d=1.1); E(38.8, 'tear')
E(39.6, 'thud', v=.8); E(40.4, 'thud', v=.9); E(41.3, 'thud', v=1.0)
# 06
for i in range(4): E(42.4 + i * .5, 'lock', v=.8)
E(44.8, 'tick'); E(45.8, 'slam', v=.8); E(46.8, 'shatter', v=.4); E(47.5, 'boom', v=.7); E(47.5, 'rise', d=3.1); E(50.6, 'biglock')
# 07
E(51.0, 'sub', v=.7); E(51.0, 'drone', d=7.8, kind='deep')
for t in (52.2, 53.2, 54.2): E(t, 'step')
for i in range(4): E(54.0 + i * .4, 'type', v=.9)
E(55.95, 'boom', v=1); E(56.3, 'sweep'); E(58.85, 'sub', v=1)
ev.sort(key=lambda e: e['t'])
open(f'{HERE}/timeline.js', 'w').write(f"// generated by gen_timeline.py\nexport const VO = {json.dumps(VO)};\nexport const EV = {json.dumps(ev)};\n")
cues = [{'t0': t, 't1': t + max(dur[k] + .6, 1.8), 'text': lines[k]['text'].replace('Lat-vair-ia', 'Latveria')} for k, t in VO.items()]
json.dump(cues, open(f'{HERE}/cues.json', 'w'), indent=1)
