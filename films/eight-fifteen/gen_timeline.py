"""Build timeline.js (picture) and cues.json (subtitles) from lines.json + voice/dur.json + voice/words.json."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
lines = json.load(open(f'{HERE}/lines.json'))
dur = json.load(open(f'{HERE}/voice/dur.json'))
words = json.load(open(f'{HERE}/voice/words.json'))

START = {'l01': 1.5, 'l02': 6.0, 'l03': 15.0, 'l04': 29.0, 'l05': 37.0, 'l06': 46.0, 'l07': 54.0,
         'l08': 64.0, 'l09': 75.0, 'l10': 86.0, 'l11': 97.0, 'l12': 103.0}
exploded = next(w[1] for w in words['l07'] if w[0].startswith('exploded'))
T = {'flash1': 26.0, 'flash2': round(START['l07'] + exploded, 2), 'bell': 101.5, 'card1': 113.5, 'card2': 124.0, 'end': 134.5}

subs, ev = [], []
prev_end = 0
for L in lines:
    t0 = START[L['id']]; t1 = t0 + max(dur[L['id']] + .6, 1.8)
    assert t0 >= prev_end - .6, f"{L['id']} overlaps the previous line"
    prev_end = t0 + dur[L['id']]
    subs.append({'t0': round(t0, 3), 't1': round(t1, 3), 'text': L['sub'].replace('|', '\n')})
    ev.append({'t': t0, 'type': 'voice', 'id': L['id']})

# foley / cue events (the mixer reads these; the picture is built to the same numbers)
for k in range(0, 13): ev.append({'t': float(k), 'type': 'tick', 'v': .35})
for k in (23, 24, 25): ev.append({'t': float(k), 'type': 'tick', 'v': 1.0})
ev += [{'t': 13.6, 'type': 'tram'}, {'t': 14.2, 'type': 'plane', 'd': 9.5},
       {'t': T['flash1'], 'type': 'flash', 'big': 1}, {'t': T['flash2'], 'type': 'flash', 'big': 0},
       {'t': 45.0, 'type': 'plane', 'd': 8.5}, {'t': T['bell'], 'type': 'bell'}]
# cranes appear (picture uses the same seed and spacing): one paper sound each
for i in range(26): ev.append({'t': 75.6 + i * (15.6 / 26) + .1, 'type': 'paper'})
ev.append({'t': 92.0, 'type': 'wings', 'd': 5.0})
ev.sort(key=lambda e: e['t'])

js = '// generated by gen_timeline.py — do not edit\n'
js += f'export const T = {json.dumps(T)};\n'
js += f'export const LINES = {json.dumps({k: [START[k], dur[k]] for k in START})};\n'
js += f'export const SUBS = {json.dumps(subs, ensure_ascii=False)};\n'
js += f'export const EV = {json.dumps(ev)};\n'
open(f'{HERE}/timeline.js', 'w').write(js)
json.dump(subs, open(f'{HERE}/cues.json', 'w'), indent=1, ensure_ascii=False)
json.dump({'T': T, 'START': START}, open(f'{HERE}/timeline.json', 'w'), indent=1)
print(T)
